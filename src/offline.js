/** 성격 설명에서 낱말을 찾아 터치 대사 묶음을 만든다 (여러 개면 합친다). 맞는 게 없으면 null */
export function personaPack(persona) {
  const text = `${persona?.name ?? ''} ${persona?.traits ?? ''}`;
  const hits = PERSONA_PACKS.filter((p) => p.words.test(text));
  if (!hits.length) return null;
  const merge = (k) => hits.flatMap((p) => p[k]);
  return { tap: merge('tap'), pet: merge('pet'), spam: merge('spam'), src: 'builtin', label: hits.map((p) => p.label).join('·') };
}
